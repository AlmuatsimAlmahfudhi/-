/** يضبط رقم النغمة لعناصر وحدة النغمات بناءً على علامة التشكيل في البينيين */
function toneOf(pinyin: string): number {
  const marks: [RegExp, number][] = [
    [/[āēīōūǖ]/, 1],
    [/[áéíóúǘ]/, 2],
    [/[ǎěǐǒǔǚ]/, 3],
    [/[àèìòùǜ]/, 4],
  ];
  for (const [re, t] of marks) if (re.test(pinyin)) return t;
  return 5;
}
function withTones(u: Unit): Unit {
  for (const l of u.lessons)
    for (const id of l.items) {
      const it = b.items[id];
      if (it && (it.type === "tone" || it.type === "syllable")) it.tone = toneOf(it.text);
    }
  return u;
}

